#!/usr/bin/env python3
# Pre-build script to generate compile_time.h with build timestamp
import os
import datetime

scriptDir = os.path.dirname(os.path.abspath(__file__))
outputFile = os.path.join(scriptDir, "src", "compile_time.h")

timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

content = f"""// Auto-generated by generate_compile_time.py
#pragma once
#define COMPILE_TIMESTAMP "{timestamp}"
"""

with open(outputFile, "w") as f:
    f.write(content)

print(f"Generated {outputFile} with timestamp {timestamp}")
