#!/usr/bin/env python3
"""Generate anti-aliased Inter fonts (Latin-1, with accents) for TFT_eSPI.

Output: src/fonts/InterFonts.h with one PROGMEM VLW array per style plus a
FONT_TABLE that DisplayUI indexes by the FONT_* ids in config.h.

Usage:  python3 tools/make_fonts.py path/to/Inter-Variable.(ttf|woff2)
Needs Pillow built with FreeType. Inter is SIL OFL 1.1 (rsms.me/inter).
"""
import struct
import sys
from pathlib import Path

from PIL import ImageFont

# (C name, px size, weight) -- order MUST match FONT_* ids in config.h (id = index + 1)
STYLES = [
    ("Inter12",  12, 400),  # FONT_XS
    ("Inter14",  14, 400),  # FONT_SM
    ("Inter16",  16, 400),  # FONT_MD
    ("Inter16B", 16, 600),  # FONT_MD_B
    ("Inter20B", 20, 700),  # FONT_LG
    ("Inter28B", 28, 700),  # FONT_XL
    ("Inter12B", 12, 600),  # FONT_XS_B
    ("Inter14B", 14, 600),  # FONT_SM_B
]
CHARS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))


def build_vlw(path, size, weight):
    font = ImageFont.truetype(str(path), size)
    try:
        font.set_variation_by_axes([weight])
    except OSError:
        pass  # static font file: weight fixed by the file
    glyphs = []
    for cp in CHARS:
        ch = chr(cp)
        mask, (x0, y0) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        if w == 0 or h == 0:
            w = h = 0
        bitmap = bytes(mask) if w and h else b""
        adv = round(font.getlength(ch))
        glyphs.append((cp, h, w, adv, -y0, x0, bitmap))
    ascent = max(g[4] for g in glyphs if g[1])
    descent = max(g[1] - g[4] for g in glyphs if g[1])
    cap = glyphs[ord("H") - 0x20][4]
    out = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return out, cap, ascent, descent


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    if not src or not src.exists():
        sys.exit(__doc__)
    root = Path(__file__).resolve().parent.parent
    dst = root / "src" / "fonts" / "InterFonts.h"
    dst.parent.mkdir(exist_ok=True)
    lines = [
        "// Generated by tools/make_fonts.py -- do not edit.",
        "// Inter (SIL OFL 1.1). Anti-aliased VLW, Latin-1 (accents).",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct FontInfo { const uint8_t* data; uint8_t cap; uint8_t ascent; uint8_t descent; };",
        "",
    ]
    table = []
    total = 0
    for name, size, weight in STYLES:
        data, cap, asc, desc = build_vlw(src, size, weight)
        total += len(data)
        lines.append(f"static const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        table.append(f"  {{ {name}, {cap}, {asc}, {desc} }},")
    lines.append("")
    lines.append("static const FontInfo FONT_TABLE[] = {")
    lines += table
    lines.append("};")
    dst.write_text("\n".join(lines) + "\n")
    print(f"wrote {dst} ({total / 1024:.1f} KB of font data)")


if __name__ == "__main__":
    main()
